// Inicialização do site
document.addEventListener("DOMContentLoaded", () => {
  // Carregar os mods
  loadMods()

  // Inicializar o alternador de tema
  initThemeToggle()

  // Inicializar os modais
  initModals()

  // Iniciar simulação de votos
  startVoteSimulation()

  // Atualizar contador total de votos
  updateTotalVotes()

  // Inicializar animação da meta
  initGoalAnimation()
})

// Função para carregar os mods
function loadMods() {
  const container = document.getElementById("mods-container")
  const template = document.getElementById("mod-card-template")
  const reactionsModal = document.getElementById("reactions-modal")
  const reactionsContainer = document.querySelector(".reactions-container")

  // Limpar o container
  container.innerHTML = ""

  // Renderizar cada mod
  modsData.forEach((mod, index) => {
    // Clonar o template
    const modCard = template.content.cloneNode(true)

    // Preencher os dados do mod
    const img = modCard.querySelector(".mod-image img")
    img.src = `assets/images/${mod.image}`
    img.alt = mod.title

    modCard.querySelector(".mod-version").textContent = `v${mod.version}`
    modCard.querySelector(".mod-title").textContent = mod.title
    modCard.querySelector(".mod-desc").textContent = mod.desc

    // Configurar botão de download
    const downloadBtn = modCard.querySelector(".download-btn")
    downloadBtn.addEventListener("click", () => {
      openDownloadModal(mod)
    })

    // Obter votos do localStorage ou usar o valor inicial
    const savedVotes = getVotesFromStorage(mod.id) || mod.votes

    const voteCount = modCard.querySelector(".vote-count")
    voteCount.textContent = savedVotes

    // Salvar votos iniciais no localStorage se não existirem
    if (!getVotesFromStorage(mod.id)) {
      localStorage.setItem(`mod_votes_${mod.id}`, savedVotes)
    }

    // Obter reação atual do usuário (se houver)
    const userReaction = localStorage.getItem(`mod_reaction_${mod.id}`) || "like"

    // Atualizar ícone de reação
    const currentReaction = modCard.querySelector(".current-reaction i")
    updateReactionIcon(currentReaction, userReaction)

    // Adicionar evento ao botão de reação
    const reactionTrigger = modCard.querySelector(".reaction-trigger")
    reactionTrigger.addEventListener("click", (e) => {
      e.stopPropagation()

      // Posicionar o modal de reações
      const rect = reactionTrigger.getBoundingClientRect()
      reactionsContainer.style.left = `${rect.left}px`
      reactionsContainer.style.top = `${rect.top - 70}px`

      // Mostrar o modal
      reactionsModal.style.display = "block"

      // Armazenar o ID do mod atual para referência
      reactionsModal.setAttribute("data-mod-id", mod.id)
      reactionsModal.setAttribute("data-trigger-element", `.mod-card:nth-child(${index + 1}) .reaction-trigger`)
    })

    // Adicionar o card ao container com delay para animação
    const cardElement = modCard.querySelector(".mod-card")
    cardElement.style.opacity = "0"
    cardElement.style.transform = "translateY(20px)"
    container.appendChild(cardElement)

    setTimeout(() => {
      cardElement.style.transition = "opacity 0.5s ease, transform 0.5s ease"
      cardElement.style.opacity = "1"
      cardElement.style.transform = "translateY(0)"
    }, 100 * index)
  })

  // Configurar os botões de reação
  const reactionButtons = document.querySelectorAll(".reaction-btn")
  reactionButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const reaction = button.getAttribute("data-reaction")
      const modId = reactionsModal.getAttribute("data-mod-id")
      const triggerSelector = reactionsModal.getAttribute("data-trigger-element")

      if (modId) {
        // Armazenar a reação do usuário
        localStorage.setItem(`mod_reaction_${modId}`, reaction)

        // Incrementar votos
        const newVotes = incrementVote(modId)

        // Atualizar UI
        const triggerElement = document.querySelector(triggerSelector)
        if (triggerElement) {
          const currentReaction = triggerElement.querySelector(".current-reaction i")
          const voteCount = triggerElement.querySelector(".vote-count")

          // Atualizar ícone e contagem
          updateReactionIcon(currentReaction, reaction)
          voteCount.textContent = newVotes

          // Efeito visual
          triggerElement.classList.add("voted")
          setTimeout(() => {
            triggerElement.classList.remove("voted")
          }, 500)
        }

        // Atualizar contador total com animação
        updateTotalVotes(true)
      }

      // Fechar o modal de reações
      reactionsModal.style.display = "none"
    })
  })
}

// Função para obter votos do localStorage
function getVotesFromStorage(modId) {
  const votes = localStorage.getItem(`mod_votes_${modId}`)
  return votes ? Number.parseInt(votes) : null
}

// Função para incrementar voto
function incrementVote(modId) {
  const currentVotes = getVotesFromStorage(modId)
  const newVotes = currentVotes + 1
  localStorage.setItem(`mod_votes_${modId}`, newVotes)
  return newVotes
}

// Função para atualizar o contador total de votos
function updateTotalVotes(showAnimation = false) {
  const totalVotesElement = document.getElementById("total-votes")
  let totalVotes = 0

  // Buscar todos os votos no localStorage
  for (let i = 0; i < localStorage.length; i++) {
    const key = localStorage.key(i)
    if (key.startsWith("mod_votes_")) {
      totalVotes += Number.parseInt(localStorage.getItem(key))
    }
  }

  // Animar a contagem
  animateCounter(totalVotesElement, Number.parseInt(totalVotesElement.textContent) || 0, totalVotes)

  // Mostrar animação de +1 se solicitado
  if (showAnimation) {
    showVoteAnimation()
  }
}

// Função para animar contador
function animateCounter(element, start, end) {
  const duration = 800
  const startTime = performance.now()

  function updateCounter(currentTime) {
    const elapsedTime = currentTime - startTime
    const progress = Math.min(elapsedTime / duration, 1)
    const currentValue = Math.floor(start + (end - start) * progress)

    element.textContent = currentValue

    if (progress < 1) {
      requestAnimationFrame(updateCounter)
    }
  }

  requestAnimationFrame(updateCounter)
}

// Função para mostrar animação de +1 no contador de votos
function showVoteAnimation() {
  const voteCounter = document.getElementById("vote-counter")
  const animation = document.createElement("span")
  animation.className = "vote-animation"
  animation.textContent = "+1"

  voteCounter.appendChild(animation)

  // Remover o elemento após a animação
  setTimeout(() => {
    voteCounter.removeChild(animation)
  }, 1000)
}

// Simulação de recebimento de votos de outros usuários
function startVoteSimulation() {
  // Verificar se já existe um ID de simulação
  if (!localStorage.getItem("simulation_id")) {
    localStorage.setItem("simulation_id", Date.now().toString())
  }

  // Atualizar votos a cada 8-20 segundos
  setInterval(
    () => {
      // Escolher um mod aleatório para receber voto
      const modIds = ["mod1", "mod2", "mod3", "mod4", "mod5"]
      const randomModId = modIds[Math.floor(Math.random() * modIds.length)]

      // Incrementar voto
      const currentVotes = getVotesFromStorage(randomModId)
      const newVotes = currentVotes + 1
      localStorage.setItem(`mod_votes_${randomModId}`, newVotes)

      // Atualizar interface
      const voteCountElement = document.querySelector(
        `.mod-card:nth-child(${modIds.indexOf(randomModId) + 1}) .vote-count`,
      )

      if (voteCountElement) {
        voteCountElement.textContent = newVotes

        // Efeito visual
        const voteBtn = voteCountElement.closest(".vote-btn")
        voteBtn.classList.add("voted")
        setTimeout(() => {
          voteBtn.classList.remove("voted")
        }, 500)
      }

      // Atualizar contador total com animação
      updateTotalVotes(true)
    },
    Math.random() * 12000 + 8000,
  ) // Entre 8 e 20 segundos
}

// Inicializar o alternador de tema
function initThemeToggle() {
  const themeToggle = document.getElementById("theme-toggle")

  // Verificar se há um tema salvo
  const savedTheme = localStorage.getItem("site-theme")
  if (savedTheme) {
    document.documentElement.setAttribute("data-theme", savedTheme)
    themeToggle.checked = savedTheme === "feminine"
  }

  // Alternar entre os temas
  themeToggle.addEventListener("change", () => {
    const newTheme = themeToggle.checked ? "feminine" : "masculine"
    document.documentElement.setAttribute("data-theme", newTheme)
    localStorage.setItem("site-theme", newTheme)
  })
}

// Inicializar os modais
function initModals() {
  // Modal de download
  const downloadModal = document.getElementById("download-modal")

  // Modal de doação
  const donateModal = document.getElementById("donate-modal")
  const donateBtn = document.querySelector(".donate-trigger")

  // Modal de participação na meta
  const goalModal = document.getElementById("goal-modal")
  const goalParticipateBtn = document.querySelector(".goal-participate-btn")

  // Modal de reações
  const reactionsModal = document.getElementById("reactions-modal")
  const reactionsContainer = document.querySelector(".reactions-container")

  // Botões de fechar
  const closeButtons = document.querySelectorAll(".close-modal")

  // Abrir modal de doação
  donateBtn.addEventListener("click", () => {
    donateModal.style.display = "block"
    document.body.style.overflow = "hidden"
  })

  // Abrir modal de participação na meta
  if (goalParticipateBtn) {
    goalParticipateBtn.addEventListener("click", () => {
      goalModal.style.display = "block"
      document.body.style.overflow = "hidden"
    })
  }

  // Opção PIX na doação
  const pixOption = document.getElementById("pix-option")
  const pixContainer = document.getElementById("pix-container")

  if (pixOption && pixContainer) {
    pixOption.addEventListener("click", (e) => {
      e.preventDefault()

      // Toggle do container PIX
      const isVisible = pixContainer.style.display === "block"
      pixContainer.style.display = isVisible ? "none" : "block"

      // Toggle da classe ativa
      document.querySelectorAll(".donate-option").forEach((opt) => opt.classList.remove("active"))

      if (!isVisible) {
        pixOption.classList.add("active")
      }
    })
  }

  // Fechar modais
  closeButtons.forEach((button) => {
    button.addEventListener("click", () => {
      downloadModal.style.display = "none"
      donateModal.style.display = "none"
      goalModal.style.display = "none"
      document.body.style.overflow = "auto"

      // Resetar estado dos containers
      if (pixContainer) {
        pixContainer.style.display = "none"
      }
      document.querySelectorAll(".donate-option").forEach((opt) => opt.classList.remove("active"))
    })
  })

  // Fechar ao clicar fora do modal
  window.addEventListener("click", (e) => {
    if (e.target === downloadModal) {
      downloadModal.style.display = "none"
      document.body.style.overflow = "auto"
    }
    if (e.target === donateModal) {
      donateModal.style.display = "none"
      document.body.style.overflow = "auto"

      // Resetar estado dos containers
      if (pixContainer) {
        pixContainer.style.display = "none"
      }
      document.querySelectorAll(".donate-option").forEach((opt) => opt.classList.remove("active"))
    }
    if (e.target === goalModal) {
      goalModal.style.display = "none"
      document.body.style.overflow = "auto"
    }
    if (e.target === reactionsModal) {
      reactionsModal.style.display = "none"
    }
  })

  // Copiar código PIX
  const copyPixBtns = document.querySelectorAll(".copy-pix-btn")
  copyPixBtns.forEach((btn) => {
    btn.addEventListener("click", () => {
      // Simulação de cópia de código PIX (substituir com código real depois)
      navigator.clipboard.writeText("00000000000000000000000000").then(() => {
        const originalText = btn.innerHTML
        btn.innerHTML = '<i class="fas fa-check"></i> Copiado!'

        setTimeout(() => {
          btn.innerHTML = originalText
        }, 2000)
      })
    })
  })
}

// Abrir o modal de download
function openDownloadModal(mod) {
  const modal = document.getElementById("download-modal")
  const modalTitle = document.getElementById("modal-title")
  const modalImage = document.getElementById("modal-image")
  const versionList = document.getElementById("version-list")

  // Preencher os dados do modal
  modalTitle.textContent = mod.title
  modalImage.src = `assets/images/${mod.image}`
  modalImage.alt = mod.title

  // Limpar a lista de versões
  versionList.innerHTML = ""

  // Adicionar as versões disponíveis
  mod.versions.forEach((version) => {
    const versionHeader = document.createElement("div")
    versionHeader.className = "version-header"
    versionHeader.innerHTML = `
      <h4>Versão ${version.version}</h4>
      <span class="version-date">${version.date}</span>
    `
    versionList.appendChild(versionHeader)

    // Adicionar as opções de download para esta versão
    version.options.forEach((option) => {
      const li = document.createElement("li")
      li.className = "version-item"

      li.innerHTML = `
        <div class="version-info">
          <span class="version-option">${option.name}</span>
        </div>
        <button class="version-button" data-link="${option.link}">
          <i class="fas fa-download"></i> Download
        </button>
      `

      // Adicionar evento de clique no botão de download
      const downloadBtn = li.querySelector(".version-button")
      downloadBtn.addEventListener("click", () => {
        window.location.href = option.link
      })

      versionList.appendChild(li)
    })
  })

  // Exibir o modal
  modal.style.display = "block"
  document.body.style.overflow = "hidden"
}

// Função para atualizar o ícone de reação
function updateReactionIcon(element, reaction) {
  if (!element) return

  // Remover classes de ícone anteriores
  element.className = ""

  // Adicionar nova classe de ícone
  switch (reaction) {
    case "like":
      element.className = "fas fa-thumbs-up"
      element.style.color = "#2563eb"
      break
    case "love":
      element.className = "fas fa-heart"
      element.style.color = "#f43f5e"
      break
    case "wow":
      element.className = "fas fa-surprise"
      element.style.color = "#eab308"
      break
    case "sad":
      element.className = "fas fa-sad-tear"
      element.style.color = "#6366f1"
      break
    case "angry":
      element.className = "fas fa-angry"
      element.style.color = "#ef4444"
      break
    default:
      element.className = "fas fa-thumbs-up"
      element.style.color = ""
  }
}

// Função para inicializar a animação da meta
function initGoalAnimation() {
  const progressBar = document.querySelector(".progress-bar")

  if (progressBar) {
    // Definir largura inicial como 0%
    progressBar.style.width = "0%"

    // Animar após um pequeno delay para garantir que a página seja carregada
    setTimeout(() => {
      progressBar.style.width = "0%"
    }, 500)
  }
}
